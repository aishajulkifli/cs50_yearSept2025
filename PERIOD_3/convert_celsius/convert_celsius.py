celsius = input("Enter temperature in Celsiius: ") #Get user input

fahrenheit = (int(celsius) * 9/5) + 32      #Convert Celsius to Fahrenheit. 32 is the freezing point of water in Fahrenheit, and 9/5 is the conversion factor from Celsius to Fahrenheit.
print(f"{celsius} degrees Celsius is equal to {fahrenheit} degrees Fahrenheit.") #Print the result
